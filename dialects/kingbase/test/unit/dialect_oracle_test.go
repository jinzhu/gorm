func TestKingbaseOracleRemoveIndexQuotedPath(t *testing.T) {
	db, mock, close := openMockGorm(t, testDialectKingbaseOracle)
	defer close()
	for _, c := range []struct{ table, index, sql string }{
		{`"APP.With.Dot"."Order"`, `"Idx.With.Dot"`, `DROP INDEX "APP.With.Dot"."Idx.With.Dot"`},
		{`APP.Users`, `"Other"."Index"`, `DROP INDEX "Other"."Index"`},
		{`Users`, `select`, `DROP INDEX "select"`},
	} {
		mock.ExpectExec("^" + regexp.QuoteMeta(c.sql) + "$").WillReturnResult(sqlmock.NewResult(0, 0))
		if err := db.Dialect().RemoveIndex(c.table, c.index); err != nil {
			t.Fatal(err)
		}
	}
	failure := errors.New("DROP denied")
	mock.ExpectExec("^" + regexp.QuoteMeta(`DROP INDEX "APP"."Missing"`) + "$").WillReturnError(failure)
	if err := db.Dialect().RemoveIndex("APP.Users", "Missing"); err != failure {
		t.Fatalf("driver error lost: %v", err)
	}
	if err := mock.ExpectationsWereMet(); err != nil {
		t.Fatal(err)
	}
}

func TestKingbaseOracleGeneratedNamesPreserveDistinctSuffixes(t *testing.T) {
	d := kb.NewKingbaseDialect(kb.KbModeOracle)
	// 上游命名器会把非 ASCII 字符替换为下划线；保留足够 ASCII 字节，
	// 以覆盖该步骤之后的名称缩短逻辑。
	table := strings.Repeat("表long", 35)
	a, b := d.BuildKeyName("fk", table, "parent_a"), d.BuildKeyName("fk", table, "parent_b")
	if a == b || len(a) > 63 || len(b) > 63 || !utf8.ValidString(a) || !utf8.ValidString(b) || a != d.BuildKeyName("fk", table, "parent_a") {
		t.Fatalf("unstable, truncated or colliding names: %q %q", a, b)
	}
	db, mock, close := openMockGorm(t, testDialectKingbaseOracle)
	defer close()
	mock.ExpectQuery("^SHOW max_identifier_length$").WillReturnRows(sqlmock.NewRows([]string{"max_identifier_length"}).AddRow(48))
	name := db.Dialect().BuildKeyName("fk", table, "parent_a")
	if len(name) > 48 || !utf8.ValidString(name) {
		t.Fatalf("instance identifier limit ignored: %q", name)
	}
	if err := mock.ExpectationsWereMet(); err != nil {
		t.Fatal(err)
	}
}
